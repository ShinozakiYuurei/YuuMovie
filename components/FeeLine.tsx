/**
 * 手續費藥丸（場次頁 / 戲院列表頁 / 戲院詳情頁共用）
 *
 * ===== 為什麼是一個組件，而不是各頁面自己寫 JSX =====
 *
 * 這一行在三個地方出現。2026-09-21 一天之內被用戶改了五次文案：
 *   「$10 手續費」→ 加「（已含）」→「（已含於票價）」→ 外加也補「（結帳另加）」
 *   → 全部去掉，回到「$xx 手續費」+ 統一長度
 *
 * 每次都是三處一起改，且中間確實漏改過一處（場次頁漏了，靠事後 grep 才發現）。
 * 抽成組件後，文案與樣式只有這一份，改一次三處同步。
 *
 * ★ 2026-09-26 用戶：「現在看著突兀不協調」，要求改文字與佈局：
 *   原先是裸的一行文字（「$6 手續費」/「— 手續費未確認」）夾在地址與按鈕之間，
 *   沒有任何容器，讀起來像地址的第二行；「—」尤其像壞掉的數字。
 *   改為**藥丸標籤**（hkm-chip），與卡片上的規格標籤同一視覺語言 ——
 *   卡片裡其餘的中繼資訊都是藥丸，手續費也該是藥丸，才不顯得突兀。
 *
 * ===== 文案順序為什麼改成「手續費 + 金額」=====
 *
 * 原先是「$6 手續費」（金額在前）。改用藥丸後，標籤在前有三個好處：
 *   1. 中文語序本來就是「手續費 $6」，讀起來順；
 *   2. 藥丸是緊貼內容的盒子，幾張卡的標籤起點一致，
 *      掃視時先看到「這是手續費」、再看到金額，層次分明；
 *   3. 金額長度不再需要對齊（$8 / $10 各佔自己的寬度），
 *      原本為對齊而做的 .hkm-num（min-width:3ch）可以整個拿掉。
 *
 * ===== 未確認的處理 =====
 *
 * 未確認時不再顯示「—」——那個破折號看起來像壞掉的數字。
 * 改為「手續費待確認」，並只把字色調弱（.hkm-fee--unknown）。
 *
 * ★ 不加虛線邊框、不加任何額外裝飾：用戶明確要求「不要做成虛線藥丸，
 *   寧可留空也不要猜數字；未確認灰字弱化即可」。
 *   弱化到「看得見但不搶眼」就夠了，再加裝飾反而把注意力拉到一個
 *   沒有答案的欄位上。
 *
 * ★ 只改狀態的呈現方式，不編數字：院方沒有公開的固定金額時，
 *   仍然是「沒有數字」，只是不再顯示成一個破折號。
 */
export function FeeLine({
  amount,
  note,
  className = '',
}: {
  /** 每張戲票手續費（HKD）。0 = 免手續費；負值 = 待確認 */
  amount: number;
  /** hover 說明：寫明 0 元的來歷（會員豁免）與是否已含在票價內 */
  note: string;
  /** 各頁面自己的外距（如 'mt-1'）；字號與顏色由 .hkm-fee 統一給 */
  className?: string;
}) {
  return (
    /*
     * 整顆藥丸共用一個 title：滑過藥丸任何一處都能看到說明，
     * 不必對準金額兩個字。
     *
     * ★ 不再套用 .hkm-num / tabular-nums：藥丸是 inline-flex 的盒子，
     *   寬度跟著內容走，沒有「$8 和 $10 要一樣長」的問題。
     */
    <span
      className={`hkm-chip hkm-fee ${amount < 0 ? 'hkm-fee--unknown' : ''} ${className}`}
      title={note}
    >
      {amount < 0 ? '手續費待確認' : `手續費 $${amount}`}
    </span>
  );
}
